"""Writes engine/dxf/r2000-template.ts: an empty DXF R2000 drawing made by ezdxf, for the
exporter to fill (P1.3). Run with the tools venv: tools/.venv/bin/python tools/make_dxf_template.py

The template holds what every file needs: header, tables, the model/paper space records,
layouts and dictionaries, millimetre units, the DASHED linetype, the PLANCRAFT application id
and the opening symbols (unit-size blocks drawn on layer 0, scaled where they are inserted).
"""
import io
import json
import pathlib

import ezdxf

doc = ezdxf.new("R2000", setup=False)
doc.header["$INSUNITS"] = 4  # millimetres
doc.header["$MEASUREMENT"] = 1  # metric
doc.header["$LUNITS"] = 2  # decimal
doc.header["$LWDISPLAY"] = 1  # show lineweights
doc.header["$LTSCALE"] = 1.0
doc.linetypes.add("DASHED", pattern=[300.0, 200.0, -100.0], description="Dashed __ __ __")
doc.appids.add("PLANCRAFT")

door = doc.blocks.new("DOOR")  # hinge at the origin, leaf along +y, opening width 1
door.add_line((0, 0), (0, 1))
door.add_arc((0, 0), 1, 0, 90)
window = doc.blocks.new("WINDOW")  # along +x, across the wall thickness (y from -0.5 to 0.5)
for y in (-0.25, 0.0, 0.25):
    window.add_line((0, y), (1, y))
vent = doc.blocks.new("VENTILATOR")
for y in (-0.2, 0.2):
    vent.add_line((0, y), (1, y))
opening = doc.blocks.new("OPENING")
opening.add_line((0, 0), (1, 0))

stream = io.StringIO()
doc.write(stream)
text = stream.getvalue()
out = pathlib.Path(__file__).resolve().parent.parent / "engine" / "dxf" / "r2000-template.ts"
out.write_text(
    "// Generated by tools/make_dxf_template.py with ezdxf "
    + ezdxf.__version__
    + ". Do not edit; regenerate.\n"
    + "export const R2000_TEMPLATE = "
    + json.dumps(text)
    + ";\n"
)
print(f"wrote {out} ({len(text)} characters)")
